<p>Диаграмма с несколькими пулами и сообщениями называется <b>коллаборацией</b>: видно, кто что делает и кто кому что отправляет. Существует и <b>хореография</b>, где показаны только обмены сообщениями между участниками без их внутренних процессов, но на практике аналитики пользуются коллаборациями.</p>

